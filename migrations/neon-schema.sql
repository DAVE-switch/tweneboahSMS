CREATE TABLE IF NOT EXISTS schema_migrations (
  version VARCHAR(100) PRIMARY KEY,
  applied_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS users (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR(160) NOT NULL,
  email VARCHAR(190) NOT NULL UNIQUE,
  role VARCHAR(32) NOT NULL CHECK (role IN ('Director','Administrator')),
  salt CHAR(32) NOT NULL,
  password_hash CHAR(128) NOT NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS sessions (
  token_hash CHAR(64) PRIMARY KEY,
  user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  csrf VARCHAR(64) NOT NULL,
  expires_at BIGINT NOT NULL
);

CREATE TABLE IF NOT EXISTS classes (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR(120) NOT NULL UNIQUE,
  level VARCHAR(80),
  is_active BOOLEAN NOT NULL DEFAULT TRUE,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS academic_years (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR(40) NOT NULL UNIQUE,
  start_date DATE,
  end_date DATE,
  is_current BOOLEAN NOT NULL DEFAULT FALSE,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS students (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  student_code VARCHAR(32) NOT NULL UNIQUE,
  full_name VARCHAR(160) NOT NULL,
  date_of_birth DATE,
  gender VARCHAR(32),
  admission_date DATE NOT NULL,
  class_name VARCHAR(120) NOT NULL,
  academic_year VARCHAR(40),
  address VARCHAR(500),
  status VARCHAR(32) NOT NULL DEFAULT 'Active' CHECK (status IN ('Active','On hold','Withdrawn','Transferred','Graduated')),
  guardian_name VARCHAR(160),
  guardian_relationship VARCHAR(80),
  guardian_phone VARCHAR(48),
  guardian_alt_phone VARCHAR(48),
  guardian_email VARCHAR(190),
  notes TEXT,
  class_id BIGINT REFERENCES classes(id),
  academic_year_id BIGINT REFERENCES academic_years(id),
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS students_name_idx ON students(full_name);

CREATE TABLE IF NOT EXISTS guardians (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  full_name VARCHAR(160) NOT NULL,
  relationship VARCHAR(80),
  phone VARCHAR(48),
  alt_phone VARCHAR(48),
  email VARCHAR(190),
  address VARCHAR(500),
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS guardians_phone_idx ON guardians(phone);

CREATE TABLE IF NOT EXISTS student_guardians (
  student_id BIGINT NOT NULL REFERENCES students(id),
  guardian_id BIGINT NOT NULL REFERENCES guardians(id),
  relationship VARCHAR(80),
  is_primary BOOLEAN NOT NULL DEFAULT FALSE,
  is_emergency_contact BOOLEAN NOT NULL DEFAULT FALSE,
  PRIMARY KEY (student_id, guardian_id)
);

CREATE TABLE IF NOT EXISTS enrollments (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  student_id BIGINT NOT NULL REFERENCES students(id),
  class_id BIGINT NOT NULL REFERENCES classes(id),
  academic_year_id BIGINT REFERENCES academic_years(id),
  start_date DATE NOT NULL,
  end_date DATE,
  status VARCHAR(32) NOT NULL DEFAULT 'Active' CHECK (status IN ('Active','Completed','Transferred','Cancelled')),
  notes TEXT,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS enrollments_student_year_idx ON enrollments(student_id, academic_year_id);

CREATE TABLE IF NOT EXISTS student_status_history (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  student_id BIGINT NOT NULL REFERENCES students(id),
  previous_status VARCHAR(32),
  new_status VARCHAR(32) NOT NULL,
  changed_on DATE NOT NULL,
  reason VARCHAR(500),
  changed_by BIGINT REFERENCES users(id),
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS student_status_history_student_idx ON student_status_history(student_id, changed_on);

CREATE TABLE IF NOT EXISTS fee_structures (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR(160) NOT NULL,
  amount NUMERIC(12,2) NOT NULL,
  class_id BIGINT REFERENCES classes(id),
  academic_year_id BIGINT REFERENCES academic_years(id),
  due_date DATE,
  is_active BOOLEAN NOT NULL DEFAULT TRUE,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS fee_structures_class_year_idx ON fee_structures(class_id, academic_year_id);

CREATE TABLE IF NOT EXISTS invoices (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  invoice_number VARCHAR(48) NOT NULL UNIQUE,
  student_id BIGINT NOT NULL REFERENCES students(id),
  academic_year_id BIGINT REFERENCES academic_years(id),
  issued_on DATE NOT NULL,
  due_on DATE,
  amount_total NUMERIC(12,2) NOT NULL DEFAULT 0,
  status VARCHAR(32) NOT NULL DEFAULT 'Issued' CHECK (status IN ('Draft','Issued','Partially paid','Paid','Cancelled')),
  notes TEXT,
  created_by BIGINT REFERENCES users(id),
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS invoices_student_status_idx ON invoices(student_id, status);

CREATE TABLE IF NOT EXISTS invoice_items (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  invoice_id BIGINT NOT NULL REFERENCES invoices(id) ON DELETE CASCADE,
  fee_structure_id BIGINT REFERENCES fee_structures(id),
  description VARCHAR(200) NOT NULL,
  amount NUMERIC(12,2) NOT NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS payments (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  student_id BIGINT NOT NULL REFERENCES students(id),
  amount NUMERIC(12,2) NOT NULL,
  paid_at DATE NOT NULL,
  method VARCHAR(40) NOT NULL,
  reference VARCHAR(120),
  fee_description VARCHAR(200) NOT NULL,
  academic_year VARCHAR(40),
  received_by BIGINT NOT NULL REFERENCES users(id),
  invoice_id BIGINT REFERENCES invoices(id),
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS payments_student_idx ON payments(student_id, paid_at);

CREATE TABLE IF NOT EXISTS receipts (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  payment_id BIGINT NOT NULL UNIQUE REFERENCES payments(id),
  receipt_number VARCHAR(48) NOT NULL UNIQUE,
  issued_at TIMESTAMP NOT NULL
);

CREATE TABLE IF NOT EXISTS audit_logs (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id BIGINT NOT NULL REFERENCES users(id),
  action VARCHAR(100) NOT NULL,
  entity VARCHAR(80) NOT NULL,
  entity_id BIGINT,
  details TEXT,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
